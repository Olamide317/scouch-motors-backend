import mongoose from "mongoose";

const { Schema } = mongoose;

const paymentSchema = new Schema(
  {
    // Booking associated with this transaction.
    booking: {
      type: Schema.Types.ObjectId,
      ref: "Booking",
      required: true,
      immutable: true,
      index: true,
    },

    // Customer who owns the booking.
    customer: {
      type: Schema.Types.ObjectId,
      ref: "User",
      required: true,
      immutable: true,
      index: true,
    },

    provider: {
      type: String,
      enum: ["paystack"],
      default: "paystack",
      immutable: true,
    },

    // Test transactions must not be treated
    // as real payments.
    environment: {
      type: String,
      enum: ["test"],
      default: "test",
      immutable: true,
    },

    // Unique reference generated by our backend.
    reference: {
      type: String,
      required: true,
      unique: true,
      immutable: true,
      match: /^[A-Za-z0-9.=-]{1,100}$/,
    },

    // Amount captured from the booking in kobo.
    amountKobo: {
      type: Number,
      required: true,
      min: 1,
      immutable: true,
      validate: {
        validator: Number.isSafeInteger,
        message: "Amount must be a safe integer",
      },
    },

    currency: {
      type: String,
      enum: ["NGN"],
      default: "NGN",
      immutable: true,
    },

    status: {
      type: String,
      enum: [
        "created",
        "initialized",
        "pending",
        "success",
        "failed",
        "abandoned",
        "refunded",
      ],
      default: "created",
    },

    // Store as a string to avoid precision loss
    // with large provider transaction IDs.
    providerTransactionId: {
      type: String,
      trim: true,
      default: null,
    },

    authorizationUrl: {
      type: String,
      default: null,
      trim: true,
    },

    initializedAt: {
      type: Date,
      default: null,
    },

    verifiedAt: {
      type: Date,
      default: null,
    },

    paidAt: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  },
);

// Retrieve a booking's payment history.
paymentSchema.index({
  booking: 1,
  createdAt: -1,
});

// Retrieve a customer's payment history.
paymentSchema.index({
  customer: 1,
  createdAt: -1,
});

// Prevent multiple unfinished payment attempts
// for the same booking.
paymentSchema.index(
  { booking: 1 },
  {
    name: "one_open_payment_per_booking",
    unique: true,
    partialFilterExpression: {
      status: {
        $in: ["created", "initialized", "pending"],
      },
    },
  },
);

const Payment = mongoose.model("Payment", paymentSchema);

export default Payment;
